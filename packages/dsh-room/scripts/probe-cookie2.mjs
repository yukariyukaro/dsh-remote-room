const [base, token, authority, secret] = process.argv.slice(2)
const auth = await fetch(base + '/?token=' + token, { redirect: 'manual' })
const cookie = (auth.headers.getSetCookie?.()[0] || '').split(';')[0]
const admin = async (action, input = {}) => (await fetch(base + '/api/room', { method: 'POST', headers: { cookie, 'content-type': 'application/json' }, body: JSON.stringify({ action, ...input }) })).json()
const s = await admin('state')
if (s.value?.room.phase === 'open') await admin('close')
await admin('listen')
await admin('relay.connect', { url: `wss://${authority}/tunnel`, room: 'room', secret, authority, publicUrl: `https://${authority}` })
await new Promise(r => setTimeout(r, 1500))
const invited = await admin('invite')
const invite = invited.value.invitationUrl.split('#')[1]
const join = await fetch(`https://${authority}/join/request`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ token: invite, label: 'curl' }) })
const requested = await join.json()
console.log('request', join.status, JSON.stringify(requested).slice(0, 120))
await admin('approve', { id: (await admin('state')).value.room.pending[0].id })
const status = await fetch(`https://${authority}/join/status`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(requested) })
console.log('status', status.status, 'set-cookie=', JSON.stringify(status.headers.getSetCookie?.()))
console.log('body', (await status.text()).slice(0, 80))
await admin('relay.disconnect'); await admin('close')
