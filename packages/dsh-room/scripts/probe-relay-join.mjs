import { chromium } from 'playwright'
const [base, token, authority, secret] = process.argv.slice(2)
const browser = await chromium.launch()
const ownerCtx = await browser.newContext()
const owner = await ownerCtx.newPage()
await owner.goto(`${base}/?token=${encodeURIComponent(token)}`, { waitUntil: 'domcontentloaded' })
await owner.waitForSelector('#root > *', { timeout: 30000 })
await owner.waitForTimeout(800)
const admin = (action, input = {}) => owner.evaluate(async ([action, input]) => {
  const r = await fetch('/api/room', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ action, ...input }) })
  return r.json()
}, [action, input])
const before = await admin('state')
if (before.value?.room.phase === 'open') await admin('close')
await admin('listen')
await admin('relay.connect', { url: `wss://${authority}/tunnel`, room: 'room', secret, authority, publicUrl: `https://${authority}` })
await owner.waitForTimeout(1500)
const invited = await admin('invite')
const inviteToken = invited.value.invitationUrl.split('#')[1]

const guestCtx = await browser.newContext()
const guest = await guestCtx.newPage()
const failures = []
guest.on('response', r => { if (r.status() >= 400) failures.push(r.status() + ' ' + r.url().slice(0, 110)) })
guest.on('requestfailed', r => failures.push('FAILED ' + r.url().slice(0, 110) + ' ' + r.failure()?.errorText))
guest.on('console', m => { if (m.type() === 'error') failures.push('console ' + m.text().slice(0, 110)) })
guest.on('pageerror', e => failures.push('pageerror ' + e.message.slice(0, 140)))
await guest.goto(`https://${authority}/join#${inviteToken}`, { waitUntil: 'domcontentloaded' })
await guest.getByPlaceholder('你的名字（会显示给房主）').fill('中继访客')
await guest.getByRole('button', { name: '申请加入' }).click()
await guest.waitForFunction(() => document.body.innerText.includes('已发送申请'), undefined, { timeout: 20000 })
await owner.waitForTimeout(500)
const pending = await admin('state')
await admin('approve', { id: pending.value.room.pending[0].id })
await guest.waitForTimeout(8000)
console.log('URL', guest.url())
const cookies = await guestCtx.cookies()
console.log('COOKIES', cookies.map(c => c.name + '@' + c.domain + (c.secure ? ' secure' : '')).join(', '))
console.log('BODY', (await guest.evaluate(() => document.body.innerHTML)).replace(/\s+/g, ' ').slice(0, 200))
console.log('TEXT', (await guest.evaluate(() => document.body.innerText)).replace(/\s+/g, ' ').slice(0, 120))
console.log('FAILURES', JSON.stringify(failures.slice(0, 10), null, 1))
await admin('relay.disconnect'); await admin('close')
await browser.close()
