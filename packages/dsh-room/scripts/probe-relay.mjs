import { chromium } from 'playwright'
const [base, token, authority] = process.argv.slice(2)
const browser = await chromium.launch()
const ownerCtx = await browser.newContext()
const owner = await ownerCtx.newPage()
await owner.goto(`${base}/?token=${encodeURIComponent(token)}`, { waitUntil: 'domcontentloaded' })
await owner.waitForSelector('#root > *', { timeout: 30000 })
await owner.waitForTimeout(800)
const dismiss = owner.getByRole('button', { name: '继续' })
if (await dismiss.count() > 0) await dismiss.first().click({ force: true })
const admin = (action, input = {}) => owner.evaluate(async ([action, input]) => {
  const r = await fetch('/api/room', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ action, ...input }) })
  return r.json()
}, [action, input])
const state = await admin('state')
if (state.ok && state.value.room.phase === 'open') { await admin('relay.disconnect'); await admin('close') }
await admin('listen')
const relayed = await admin('relay.connect', { url: `ws://${authority}/tunnel`, room: 'demo', secret: 'dsh-room-demo-secret-1234', authority })
console.log('relay', JSON.stringify(relayed.value?.relay))
await owner.waitForTimeout(1500)
const invited = await admin('invite')
const inviteToken = invited.value.invitationUrl.split('#')[1]

const guestCtx = await browser.newContext()
const guest = await guestCtx.newPage()
const failures = []
const errors = []
guest.on('response', r => { if (r.status() >= 400) failures.push(`${r.status()} ${r.url().slice(0, 120)}`) })
guest.on('requestfailed', r => failures.push(`FAILED ${r.url().slice(0, 120)} ${r.failure()?.errorText}`))
guest.on('console', m => { if (m.type() === 'error') errors.push(m.text().slice(0, 150)) })
guest.on('pageerror', e => errors.push('pageerror ' + e.message.slice(0, 200)))
await guest.goto(`http://${authority}/join#${inviteToken}`, { waitUntil: 'domcontentloaded' })
await guest.waitForFunction(() => document.body.innerText.includes('等待房主批准'), undefined, { timeout: 20000 })
const pending = await admin('state')
await admin('approve', { id: pending.value.room.pending[0].id })
await guest.waitForURL(u => !u.pathname.startsWith('/join'), { timeout: 30000 })
await guest.waitForTimeout(5000)
console.log('URL', guest.url())
console.log('BODY', (await guest.evaluate(() => document.body.innerHTML.slice(0, 300))).replace(/\s+/g, ' '))
console.log('TEXT', (await guest.evaluate(() => document.body.innerText)).replace(/\s+/g, ' ').slice(0, 200))
console.log('FAILURES', JSON.stringify(failures.slice(0, 12), null, 1))
console.log('ERRORS', JSON.stringify(errors.slice(0, 8), null, 1))
await guest.screenshot({ path: 'artifacts/e2e/relay-debug.png' })
await admin('relay.disconnect'); await admin('close')
await browser.close()
