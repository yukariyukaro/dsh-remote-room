export type CopyKey = keyof typeof zh
export type Translate = (key: CopyKey, values?: Record<string, string>) => string

/** The same Chinese dictionary serves every locale until a real translation exists. */
export const en: Record<CopyKey, string> = zh

export function fill(template: string, values: Record<string, string>): string {
  return template.replace(/\{(\w+)\}/gu, (match, name: string) => values[name] ?? match)
}

/** Binds one dictionary to a stable translate function. */
export function translator(dictionary: Record<CopyKey, string> = zh): Translate {
  return (key, values) => values ? fill(dictionary[key], values) : dictionary[key]
}
